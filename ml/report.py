"""Generate docs/model_selection.md from the real artifacts (no hand-typed numbers)."""
import json

from ml import config


def main() -> None:
    sel = json.loads((config.ARTIFACTS_DIR / "model_selection.json").read_text())
    met = json.loads((config.ARTIFACTS_DIR / "metrics.json").read_text())
    card = json.loads((config.ARTIFACTS_DIR / "model_card.json").read_text())
    rows = "\n".join(
        f"| {n} | {r['cv_pr_auc_mean']:.3f} | {r['val_pr_auc']:.3f} | {r['val_roc_auc']:.3f} | `{r['best_params']}` |"
        for n, r in sel["candidates"].items())
    cm = met["confusion_matrix"]
    text = f"""# Model selection (generated by `python -m ml.report`)

Selection criterion: {sel['selection_criterion']} (never accuracy; positives are ~5% of rows).

| Model | CV PR-AUC (train) | Validation PR-AUC | Validation ROC-AUC | Best params |
|---|---|---|---|---|
{rows}

Selected: **{sel['selected']}**. Differences between candidates are small relative to the noise expected
from roughly 50 positive cases per evaluation split, so the choice is not strong evidence that one model
family is better.

Threshold: {card['threshold']:.4f}, chosen on the validation set ({card['threshold_criterion']}).
Validation precision {card['validation_precision_at_threshold']:.3f}, recall {card['validation_recall_at_threshold']:.3f}.

## Held-out test results (evaluated once)

- Test rows: {met['n_test']} ({met['n_test_positive']} positive)
- Recall {met['recall']:.3f}, precision {met['precision']:.3f}, F1 {met['f1']:.3f}, specificity {met['specificity']:.3f}
- ROC-AUC {met['roc_auc']:.3f}, PR-AUC {met['pr_auc']:.3f} (dummy baseline PR-AUC {met['dummy_baseline']['pr_auc']:.3f})
- Brier {met['brier']:.4f} (prevalence baseline {met['brier_baseline_prevalence']:.4f})
- Confusion matrix: TN {cm['tn']}, FP {cm['fp']}, FN {cm['fn']}, TP {cm['tp']}
- Expected calibration error (5 quantile bins): {met['ece_5_quantile_bins']:.4f}

## Reading these numbers honestly

- Precision is low: most people flagged as higher than typical did not have a stroke in this data.
  The threshold trades many false alarms for fewer missed cases.
- The calibration check ({met['probability_display_criterion']}) returned
  `{met['probability_display_supported']}`, but with this few positives that check is noisy. The UI should
  prefer the lower / moderate / higher band and treat any percentage as approximate.
- This is a single split. Confidence intervals were not computed.
"""
    (config.ROOT / "docs" / "model_selection.md").write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
