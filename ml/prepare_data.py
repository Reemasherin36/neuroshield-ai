"""Load + validate the Kaggle CSV, make the stratified split, write the EDA report."""
import hashlib
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd
from sklearn.model_selection import train_test_split

from ml import config


class SetupRequired(Exception):
    """Dataset missing or invalid; message is shown to the user as-is."""


def find_csv():
    files = sorted(config.DATA_DIR.glob("*.csv"))
    if not files:
        raise SetupRequired(
            "No CSV found in data/. Download the Kaggle 'Stroke Prediction Dataset' "
            "(fedesoriano) and place it in data/ (see data/README.md)."
        )
    return files[0]


def file_hash(path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load_data() -> pd.DataFrame:
    path = find_csv()
    df = pd.read_csv(path, na_values=["N/A", "NA", ""])
    missing = [c for c in config.REQUIRED_COLUMNS if c not in df.columns]
    if missing:
        raise SetupRequired(f"The CSV is missing required columns: {missing}")
    df["bmi"] = pd.to_numeric(df["bmi"], errors="coerce")
    return df


def get_splits(df: pd.DataFrame):
    """Stratified 60/20/20 split with a fixed seed. Returns (train, val, test) DataFrames."""
    X, y = df[config.FEATURES], df[config.TARGET]
    X_tr, X_tmp, y_tr, y_tmp = train_test_split(
        X, y, test_size=0.4, stratify=y, random_state=config.SEED)
    X_val, X_te, y_val, y_te = train_test_split(
        X_tmp, y_tmp, test_size=0.5, stratify=y_tmp, random_state=config.SEED)
    return (X_tr, y_tr), (X_val, y_val), (X_te, y_te)


def write_eda(df: pd.DataFrame) -> None:
    config.ARTIFACTS_DIR.mkdir(exist_ok=True)
    docs = config.ROOT / "docs"
    docs.mkdir(exist_ok=True)
    raw = pd.read_csv(find_csv(), dtype=str, keep_default_na=False)  # keep "N/A" as text so it can be counted
    bmi_strings = int((raw["bmi"] == "N/A").sum())
    counts = df[config.TARGET].value_counts()
    lines = [
        "# Exploratory data analysis (generated by `python -m ml.prepare_data`)", "",
        f"- Rows: {len(df)}, columns: {df.shape[1]}",
        f"- Duplicate ids: {int(df['id'].duplicated().sum())}",
        f"- BMI cells stored as the literal string 'N/A' in the raw file: {bmi_strings}",
        f"- Missing BMI after parsing: {int(df['bmi'].isna().sum())}",
        (f"- Stroke = 0: {int(counts.get(0, 0))}, stroke = 1: {int(counts.get(1, 0))} "
         f"({df[config.TARGET].mean():.2%} positive)"),
        f"- gender values: {df['gender'].value_counts().to_dict()}",
        f"- smoking_status values: {df['smoking_status'].value_counts().to_dict()}",
        f"- work_type values: {df['work_type'].value_counts().to_dict()}", "",
        "## Numeric summary", "",
        df[config.FEATURES_NUMERIC].describe().round(2).to_markdown(), "",
        "## Stroke rate by smoking_status (note 'Unknown' is a category, not missing-at-random)", "",
        df.groupby("smoking_status")[config.TARGET].agg(["count", "mean"]).round(4).to_markdown(), "",
        "## Limitations seen in the data", "",
        "- Very few positive cases, so metrics on a 20% test split rest on few events and are noisy.",
        "- BMI and glucose contain high outliers; they were kept (not removed) and the scaler is fit on train only.",
        "- One row has gender 'Other'; the encoder ignores unseen categories.",
        "- Dataset provenance on Kaggle is limited; it is not a clinical cohort.",
        "- Children are included (age min below 1), which strongly affects work_type and smoking_status.",
        "", "Plots: `artifacts/eda_*.png`",
    ]
    (docs / "eda.md").write_text("\n".join(lines), encoding="utf-8")

    fig, ax = plt.subplots(figsize=(4, 3))
    counts.sort_index().plot.bar(ax=ax, color=["#0f766e", "#0b2545"])
    ax.set(title="Class balance", xlabel="stroke", ylabel="rows")
    fig.tight_layout(); fig.savefig(config.ARTIFACTS_DIR / "eda_class_balance.png", dpi=120); plt.close(fig)
    fig, axes = plt.subplots(1, 3, figsize=(10, 3))
    for ax, col in zip(axes, config.FEATURES_NUMERIC, strict=True):
        df[col].dropna().plot.hist(ax=ax, bins=30, color="#0f766e"); ax.set_title(col)
    fig.tight_layout(); fig.savefig(config.ARTIFACTS_DIR / "eda_distributions.png", dpi=120); plt.close(fig)


if __name__ == "__main__":
    try:
        data = load_data()
        write_eda(data)
        print("EDA written to docs/eda.md; rows:", len(data))
    except SetupRequired as e:
        print("SETUP REQUIRED:", e); sys.exit(1)
